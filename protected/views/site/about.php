
<h2>About Ride4Ride App:</h2>

<p>Ride4Ride could be the best bar app ever created! We have a mapping system for you to see bars in your area that you may never know exist. 
We have colored these bar icons so you can easily see if the bars are nearing their happy hour, if they are currently having happy hour or 
if they are running a "hot" 2 hour special (Only for our members). Save money by finding the specials and have fun doing it by finding the new 
hot spots in your neighborhood. We are trying to add new bars all the time for you to get the best deals in town.</p>

<p>Our unique app also has an all new way of getting to and from your drinking destinations with our ride trading platform. 
First you need to sign up a username. If you are the first of your friends to use this app you should start a "Ride Tribe" 
(a community of your acquaintances and friends). You will become the chief that allows you to let in new members or kick them out. 
Now you need to start recruiting trusted friends that you would feel comfortable with giving and receiving rides from.
 You can add up to 50 of your friends and their friends to build a great community. Posting your rides is easy with our mapping software.
  Each new member gets 1 free Zoken (our online currency) to get started and pay for your first ride. You may purchase more or give rides to your
Ride Tribe members to earn some. Go back and fourth giving and receiving safe rides and prevent getting a duii.
 It will take a little work getting your friends to all join up, but when you have 50 members, you should easily be able to get
  rides to and from drinking destinations.</p> 




